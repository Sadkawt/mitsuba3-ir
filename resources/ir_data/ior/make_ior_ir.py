#!/usr/bin/env python3
"""
Generate the infrared optical-constant files ``<Material>_ir.{eta,k}.spd``
in this directory.

Sources
-------
* Metals Ag, Al, Au, Be, Cr, Cu, Ni, Pd, Pt, Ti, W: Lorentz-Drude model with
  the parameters of Rakic et al., Appl. Opt. 37, 5271 (1998), evaluated
  analytically (mitsuba.ir.materials.drude_lorentz_nk). The parameters were
  verified against the refractiveindex.info tabulation of the same model
  (max. relative deviation 1.3e-4 over 0.3-12.4 um).
* All other materials: pages of the refractiveindex.info database
  (https://refractiveindex.info, CC0 1.0 public domain), converted with
  mitsuba.ir.materials.rii_to_nk. Run

      python make_ior_ir.py --rii-dir <directory with the YAML pages>

  The YAML pages are fetched from
  https://github.com/polyanskiy/refractiveindex.info-database (database/data/main/...).

Wavelength grid: 300 nm - 20 um, 300 log-spaced points, plus the end points of
each source's range; outside the source range the nearest value is held and
the ``.spd`` header states the valid range.
"""

import argparse
import os
import sys
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '..', '..', 'src', 'python', 'python'))
from ir import materials as irm  # noqa: E402

GRID = np.geomspace(300.0, 20000.0, 300)

# name -> list of (yaml file, lambda_min_nm, lambda_max_nm) pieces, concatenated in order
RII_SOURCES = {
    'Fe_ir':        [('Fe_nk_Querry.yml', 300, 20000)],
    'Si_ir':        [('Si_nk_Franta-300K.yml', 300, 20000)],
    'Ge_ir':        [('Ge_nk_Amotchkina.yml', 400, 2000), ('Ge_nk_Burnett.yml', 2000, 14000)],
    'ZnSe_ir':      [('ZnSe_nk_Querry.yml', 500, 20000)],
    'ZnS_ir':       [('ZnS_nk_Querry.yml', 300, 20000)],
    'Sapphire_ir':  [('Al2O3_nk_Querry-o.yml', 300, 20000)],
    'CaF2_ir':      [('CaF2_nk_Li.yml', 300, 12000)],
    'BaF2_ir':      [('BaF2_nk_Querry.yml', 300, 20000)],
    'NaCl_ir':      [('NaCl_nk_Querry.yml', 300, 20000)],
    'SiO2glass_ir': [('SiO2_nk_Franta-25C.yml', 300, 20000)],
    'H2O_ir':       [('H2O_nk_Hale.yml', 300, 20000)],
}


K_FLOOR = 1e-8   # Mitsuba's irregular spectra reject all-zero tables; k = 1e-8 is physically negligible


def write_pair(name, lam, n, k, header):
    k = np.maximum(np.asarray(k, dtype=np.float64), K_FLOOR)
    irm.write_spd(os.path.join(HERE, f'{name}.eta.spd'), lam, n, header + ['Column 2: refractive index n'])
    irm.write_spd(os.path.join(HERE, f'{name}.k.spd'), lam, k,
                  header + [f'Column 2: extinction coefficient k (floored at {K_FLOOR:g}; sources giving '
                            f'only n are transparent in their stated range)'])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--rii-dir', help='directory with downloaded refractiveindex.info YAML pages')
    args = ap.parse_args()

    rows = []
    for metal in sorted(irm.RAKIC_LD):
        n, k = irm.drude_lorentz_nk(metal, GRID)
        header = [
            f'{metal} (infrared): Lorentz-Drude model, parameters from A. D. Rakic, A. B. Djurisic, '
            f'J. M. Elazar, M. L. Majewski, Appl. Opt. 37(22), 5271-5283 (1998), Table 1 (LD).',
            'Generated by resources/ir_data/ior/make_ior_ir.py (mitsuba.ir.materials.drude_lorentz_nk).',
            'Fit range of the paper: 0.1-6 eV (0.2-12.4 um); extrapolated as a Drude metal to 20 um.',
            'Column 1: wavelength [nm]',
        ]
        write_pair(f'{metal}_ir', GRID, n, k, header)
        rows.append((f'{metal}_ir', '300-20000 (fit 200-12400)', 'Rakic et al. 1998, Lorentz-Drude model'))

    if args.rii_dir:
        for name, pieces in RII_SOURCES.items():
            lam_all, n_all, k_all, refs = [], [], [], []
            for fname, lo, hi in pieces:
                path = os.path.join(args.rii_dir, fname)
                lam, n, k, ref = irm.rii_to_nk(path)
                src_lo, src_hi = max(lo, lam.min()), min(hi, lam.max())
                grid = GRID[(GRID >= src_lo) & (GRID <= src_hi)]
                grid = np.unique(np.concatenate([[src_lo], grid, [src_hi]]))
                lam_all.append(grid)
                n_all.append(np.interp(grid, lam, n))
                k_all.append(np.interp(grid, lam, k))
                refs.append(f'{fname}: {ref}')
            lam = np.concatenate(lam_all)
            n = np.concatenate(n_all)
            k = np.concatenate(k_all)
            lam, idx = np.unique(lam, return_index=True)
            n, k = n[idx], k[idx]
            valid = f'{lam.min():.0f}-{lam.max():.0f} nm'
            header = [f'{name}: infrared optical constants converted from the refractiveindex.info '
                      f'database (public domain, CC0 1.0).'] + \
                     [f'Source: {r}' for r in refs] + \
                     [f'Valid range: {valid}; outside, Mitsuba holds the end values.',
                      'Generated by resources/ir_data/ior/make_ior_ir.py.',
                      'Column 1: wavelength [nm]']
            write_pair(name, lam, n, k, header)
            rows.append((name, valid, '; '.join(refs)))
    else:
        print('No --rii-dir given: only the Lorentz-Drude metals were generated.')

    with open(os.path.join(HERE, 'README_ir.md'), 'w') as f:
        f.write('# Infrared optical constants (`*_ir` presets)\n\n')
        f.write('Generated by `make_ior_ir.py`; see docs/ir/IR_TECHNICAL_REPORT.md section 7.\n')
        f.write('Use with any conductor BSDF: `{"type": "roughconductor", "material": "Al_ir", ...}`.\n\n')
        f.write('| Preset | Valid range (nm) | Source |\n|---|---|---|\n')
        for name, valid, src in rows:
            f.write(f'| `{name}` | {valid} | {src} |\n')
    print(f'Wrote {len(rows)} presets.')


if __name__ == '__main__':
    main()
